def numeric_profile(case):
    return RankingProfile(status='ready',concept=case['concept'],summary='Predeclared arithmetic audit profile, not AI interpretation',
        criteria=tuple(RankingCriterion(metric,w,pref,low,high,case['concept'],'Predeclared controlled numerical objective','Synthetic client reference, not market calibration')
                       for metric,w,pref,low,high in case['criteria']),visit_context_quotes=(case['concept'],))


def offline(out,sample):
    rows=[];failures=[];rng=random.Random(44);comparisons=0
    for case in SCENARIOS:
        p=numeric_profile(case);pairs=[(copy.deepcopy(prop),competition_report(center_lat=prop['lat'],center_lng=prop['lng'],
                     data_status='unavailable',total_cards_found=0)) for prop in sample]
        bound=bind_reference_scales(p)
        expected={prop['id']:evaluate_profile(bound,prop,rep) for prop,rep in pairs}
        for prop,rep in pairs:
            score=expected[prop['id']]
            if not (0<=score['lower']<=score['upper']<=100 and 0<=score['coverage']<=1):failures.append(dict(case=case['key'],id=prop['id'],kind='bounds'))
            # Increasing rent cannot improve a scored premises-cost criterion.
            expensive=copy.deepcopy(prop);expensive['price_month']*=1.5
            new=evaluate_profile(bound,expensive,rep)
            if new['lower']>score['lower']+1e-9 or new['upper']>score['upper']+1e-9:failures.append(dict(case=case['key'],id=prop['id'],kind='cost_monotonicity'))
            rows.append(dict(scenario=case['key'],id=prop['id'],lower=score['lower'],upper=score['upper'],coverage=score['coverage'],
                             missing=[k for k,v in score['components'].items() if v['value'] is None]))
        for _ in range(10):
            changed=copy.deepcopy(pairs);rng.shuffle(changed)
            outlier=copy.deepcopy(changed[0]);outlier[0]['id']=-1;outlier[0]['price_month']=1e9;outlier[0]['area_sqm']=1e6
            changed.extend([outlier,copy.deepcopy(outlier)])
            ref=bind_reference_scales(p)
            for prop,rep in pairs:
                comparisons+=1
                if evaluate_profile(ref,prop,rep)!=expected[prop['id']]:failures.append(dict(case=case['key'],id=prop['id'],kind='candidate_dependence'))
    facts=[dict(id=p['id'],floor=asdict(extract_floor_evidence(p)),description_length=len(p.get('description') or ''),
                has_raw_provenance=bool(json.loads(p.get('raw_json') or '{}'))) for p in sample]
    # Manually inspected source anchors, not expectations generated by the model.
    checks=[]
    for identifier,expected in [(205,'source_conflict'),(797,'insufficient_facts'),(933,'insufficient_facts')]:
        prop=next(p for p in sample if p['id']==identifier);decision=assess_floor(prop,BusinessFloorProfile())
        checks.append(dict(id=identifier,expected=expected,actual=decision.analysis_status,passed=decision.analysis_status==expected))
    if not all(c['passed'] for c in checks):failures.append(dict(kind='manual_source_anchor'))
    save(out/'offline_scores.json',rows);save(out/'source_quality.json',facts);save(out/'manual_source_checks.json',checks)
    result=dict(real_listings=len(sample),scenarios=len(SCENARIOS),numerical_evaluations=len(rows),
        invariance_comparisons=comparisons,failures=failures,sources=dict(Counter(p['source'] for p in sample)),
        no_description=sum(not p.get('description') for p in sample),floor_conflicts=sum(f['floor']['conflicting'] for f in facts),
        interpretation='Arithmetic and source prechecks only; not 192 independent language evaluations or market fitness labels.')
    save(out/'offline_summary.json',result);event('offline_completed',**result)
    return result


class NetworkBudget:
    def __init__(self,limit):self.limit=limit;self.records=[];self.lock=threading.Lock()
    def wrap(self,call):
        def post(url,**kwargs):
            with self.lock:
                if len(self.records)>=self.limit:raise AITransportError('Audit HTTP budget exhausted',retryable=False)
                record=dict(start=time.monotonic(),model=kwargs.get('json',{}).get('model'));self.records.append(record)
            try:
                response=call(url,**kwargs);record['status']=response.status_code;return response
            except Exception as exc:record['error_type']=type(exc).__name__;raise
        return post


class Analyzer(TracedAnalyzer):
    def __init__(self,out,budget):
        super().__init__(out);self.budget=budget;self.http_session.post=budget.wrap(self.http_session.post);self.mode='controlled'
    async def analyze_circle(self,**kwargs):
        if self.mode=='controlled':
            return competition_report(center_lat=kwargs['center_lat'],center_lng=kwargs['center_lng'],target_business=kwargs['target_business'],
                total_cards_found=0,data_status='unavailable',data_warnings=['Synthetic access audit: live environment deliberately omitted'])
        return await super().analyze_circle(**kwargs)


class ReusingResolver(RankingProfileResolver):
    def __init__(self,analyzer,reuse_dir):
        super().__init__(analyzer);self.ready={};self.origin=str(reuse_dir) if reuse_dir else None
        if reuse_dir:
            current_metrics={metric for metrics in PROFILE_GROUPS.values() for metric in metrics}
            manifest=json.loads((reuse_dir/'manifest.json').read_text(encoding='utf-8'))
            prior={c['key']:c for c in manifest['scenario_expectations']}
            for case in SCENARIOS:
                path=reuse_dir/('profile_'+case['key']+'.json')
                if not path.exists():continue
                old=prior.get(case['key'],{})
                if old.get('business')!=case['business'] or old.get('concept')!=case['concept']:continue
                data=json.loads(path.read_text(encoding='utf-8'))
                if data['status']!='ready' or data['metadata'].get('market_integration')!='all_collected_blocks_v1':continue
                metrics={item['metric'] for item in data['criteria']}
                if 'market_fit_index' not in metrics or not metrics<=current_metrics:continue
                scenario=data['metadata'].get('scenario_contract')
                if not scenario or not scenario.get('audience_usage'):continue
                validate_scenario({k:v for k,v in scenario.items() if k not in ('sources','audience_usage')},scenario['sources'])
                p=validate_profile({k:data[k] for k in ('status','summary','criteria','questions','assumptions','visit_context_quotes','unmodeled_requirements')},
                                   case['concept'],data['model'],data['metadata'])
                self.ready[(case['business'],case['concept'])]=p

    async def resolve(self,business,concept,requirements=None,timeout_s=25):
        saved=self.ready.get((business,concept))
        if saved is not None and saved.metadata.get('client_constraints',{})==(requirements or {}):
            p=copy.deepcopy(saved);p.metadata['audit_replayed_profile_from']=self.origin
            return p
        return await super().resolve(business,concept,requirements,timeout_s)


async def live(out,budget_limit,reuse_dir=None):
    budget=NetworkBudget(budget_limit);analyzer=Analyzer(out,budget);resolver=ReusingResolver(analyzer,reuse_dir)
    profiles={};records=[];groups={m:g for g,metrics in PROFILE_GROUPS.items() for m in metrics}
    constraints=dict(target_area_sqm=None,min_area_sqm=10,max_area_sqm=2000,max_price_month=10000000,
                     max_price_sqm_year=None,competition_diameter_m=400.0,explicit_visit_context=None)
    for case in SCENARIOS:
        analyzer.current_case='profile_'+case['key'];start=time.perf_counter()
        p=await resolver.resolve(case['business'],case['concept'],constraints,timeout_s=30)
        primary=None;passed=None
        if p.status=='ready':
            scores={groups[c.metric]:c.weight for c in p.criteria}
            primary=max(scores,key=scores.get);passed=primary==case['primary'];profiles[case['key']]=p
        item=dict(case=case['key'],status=p.status,analysis_status=p.analysis_status,seconds=round(time.perf_counter()-start,2),
                  expected_primary=case['primary'],actual_primary=primary,primary_passed=passed,
                  replayed=bool(p.metadata.get('audit_replayed_profile_from')))
        records.append(item);save(out/(analyzer.current_case+'.json'),asdict(p));event('profile_completed',**item)
        save(out/'profiles_progress.json',records)
        if len(budget.records)>=budget.limit:break
    decisions=[]
    previously_passed=set()
    if reuse_dir:
        previous=json.loads((reuse_dir/'live_summary.json').read_text(encoding='utf-8'))
        previously_passed={c['case'] for c in previous['controls'] if c['exact']}
    for control in CONTROLS:
        if control['key'] in previously_passed:continue
        case=next(c for c in SCENARIOS if c['key']==control['scenario'])
        if case['key'] not in profiles or len(budget.records)>=budget.limit:continue
        analyzer.current_case=control['key'];store=PropertyStorage(str(out/(control['key']+'.db')))
        offer=CanonicalProperty(source=PlatformSource.CIAN,external_id=control['key'],title='Синтетический семантический контроль',address='Синтетическая точка, не реальное объявление',
            lat=LAT,lng=LNG,area_sqm=100,price_month=100000,price_sqm_year=12000,floor=control['floor'],description=control['description'])
        store.upsert_property(offer);engine=OptimalPropertyRecommender(store,analyzer);engine.ranking_profile_resolver=resolver
        start=time.perf_counter()
        report=await engine.find_optimal_properties(case['business'],business_concept=case['concept'],center_lat=LAT,center_lng=LNG,search_radius_m=1000,
            min_area_sqm=10,max_area_sqm=2000,max_price_month=10000000,ranking_timeout_s=30,floor_timeout_s=60,environment_timeout_s=5,fns_timeout_s=3)
        actual='eligible' if report.evaluated_count else 'rejected' if report.floor_rejected_candidates else 'needs_verification'
        item=dict(case=control['key'],scenario=case['key'],expected=control['expected'],actual=actual,
                  safe=actual!='eligible' if control['expected']!='eligible' else actual=='eligible',
                  exact=actual==('rejected' if control['expected']=='blocked' else control['expected']),seconds=round(time.perf_counter()-start,2))
        decisions.append(item);save(out/(control['key']+'_report.json'),asdict(report));event('semantic_control',**item)
        save(out/'controls_progress.json',decisions)
    real_result=None
    if 'booking' in profiles and len(budget.records)<budget.limit:
        analyzer.mode='real';analyzer.current_case='real_booking';store=real_storage(out)
        engine=OptimalPropertyRecommender(store,analyzer);engine.ranking_profile_resolver=resolver
        case=next(c for c in SCENARIOS if c['key']=='booking');start=time.perf_counter()
        report=await engine.find_optimal_properties(case['business'],business_concept=case['concept'],center_lat=LAT,center_lng=LNG,search_radius_m=18000,
            min_area_sqm=10,max_area_sqm=2000,max_price_month=10000000,max_candidates=3,ranking_timeout_s=30,floor_timeout_s=90,environment_timeout_s=45,fns_timeout_s=10)
        save(out/'real_search.json',asdict(report));real_result=dict(seconds=round(time.perf_counter()-start,2),evaluated=report.evaluated_count,
            numerical=report.numerical_matching_count,pending=len(report.floor_verification_candidates),status=report.selection_status,errors=report.analysis_errors)
        event('real_search_completed',**real_result)
    starts=sorted(r['start'] for r in budget.records)
    peak=max((sum(t-60<x<=t for x in starts) for t in starts),default=0)
    result=dict(profiles=records,controls=decisions,real_search=real_result,http_attempts=len(budget.records),http_budget=budget.limit,
                http_429=sum(r.get('status')==429 for r in budget.records),peak_requests_rolling_minute=peak,budget_exhausted=len(budget.records)>=budget.limit,
                replayed_profiles=sum(r['replayed'] for r in records),previously_passed_controls=sorted(previously_passed),
                reuse_directory=str(reuse_dir) if reuse_dir else None)
    save(out/'http_records.json',budget.records);save(out/'live_summary.json',result)
    return result


async def main():
    parser=argparse.ArgumentParser();parser.add_argument('--live',action='store_true');parser.add_argument('--http-budget',type=int,default=60)
    parser.add_argument('--reuse-ready-profiles');args=parser.parse_args()
    if not 1<=args.http_budget<=60:raise ValueError('Audit HTTP budget must be in [1,60]')
    reuse_dir=Path(args.reuse_ready_profiles).resolve() if args.reuse_ready_profiles else None
    if reuse_dir is not None and not reuse_dir.is_relative_to((ROOT/'audit').resolve()):raise ValueError('Reuse path must be inside workspace/audit')
    os.environ['NVIDIA_MIN_REQUEST_INTERVAL_S']='4'
    base=ROOT/'audit/expanded_scenarios_2026-11-04';base.mkdir(exist_ok=True)
    out=base/datetime.now(timezone(timedelta(hours=3))).strftime('run_%H%M%S_%f');out.mkdir()
    (base/'LATEST.txt').write_text(str(out),encoding='utf-8');frozen=fingerprints()
    save(out/'manifest.json',dict(fingerprints=frozen,http_budget=args.http_budget,scenario_expectations=SCENARIOS,semantic_expectations=CONTROLS,
         interpretation='Predetermined expectations, no new listing collection, saved real sample and explicitly synthetic semantic controls.'))
    sample=sample_database(out);offline_result=offline(out,sample)
    live_result=await live(out,args.http_budget,reuse_dir) if args.live else None
    result=dict(offline=offline_result,live=live_result,source_and_working_database_unchanged=frozen==fingerprints())
    save(out/'summary.json',result);event('finished',output=str(out),unchanged=result['source_and_working_database_unchanged'])


