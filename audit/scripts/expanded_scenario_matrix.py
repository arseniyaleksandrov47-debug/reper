def sample_database(out):
    source=ROOT/'data/moscow_commercial.db'
    with sqlite3.connect(source.as_uri()+'?mode=ro',uri=True) as conn:
        conn.row_factory=sqlite3.Row;rows=[dict(r) for r in conn.execute('SELECT * FROM properties ORDER BY id')]
    sample=[next(r for r in rows if r['id']==i) for i in (80,81,205)];rng=random.Random(2026110401)
    for source_name in ('cian','domclick','yandex','avito','investmoscow'):
        used={p['id'] for p in sample};pool=[r for r in rows if r['source']==source_name and r['id'] not in used];rng.shuffle(pool)
        sample.extend(pool[:5 if source_name=='investmoscow' else 4])
